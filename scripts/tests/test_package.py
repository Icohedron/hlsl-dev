def test_relocator_rejects_unmapped_and_surviving_literals_before_writing(workspace, tmp_path):
    llvm, _, _, _, site = make_install(workspace)
    stage = tmp_path / "stage"
    target = stage / "test/clang-vk/lit.site.cfg.py"
    mappings = {llvm: "share/llvm"}
    with pytest.raises(LitRelocationError, match="unmapped"):
        relocate_lit(site.read_text(), site, target, stage, mappings)
    assert not target.exists()
    body = site.read_text() + f'\nconfig.extra = "{workspace / "secret"}"\n'
    mappings.update({workspace / "offload-test-suite": "share/hlsl-test-suite",
                     workspace / "offload-golden-images": "share/hlsl-test-suite/golden-images",
                     workspace / "host-dxc/bin": "dxc/bin",
                     llvm / "build/bin": "bin"})
    with pytest.raises(LitRelocationError, match="absolute paths survive"):
        relocate_lit(body, site, target, stage, mappings)
    embedded = site.read_text() + f'\nconfig.flag = "--driver={workspace / "driver"}"\n'
    with pytest.raises(LitRelocationError, match="absolute paths survive"):
        relocate_lit(embedded, site, target, stage, mappings)
    commented = site.read_text() + f'\n# build host {workspace / "driver"}\n'
    with pytest.raises(LitRelocationError, match="absolute paths survive"):
        relocate_lit(commented, site, target, stage, mappings)
    assert not target.exists()


