def precompiled_fixture(workspace, platform="native"):
    llvm, offload, _, build, site = make_install(workspace, "llvm", platform)
    # Keep the native host compiler separate from the target install so a
    # missing host tool can be tested without invalidating the full package.
    native = llvm / "build/install/bin"
    native.mkdir(parents=True, exist_ok=True)
    split = native / "split-file"
    split.write_text(
        "#!/usr/bin/env python3\nimport pathlib,sys\n"
        "out=pathlib.Path(sys.argv[2]); out.mkdir(parents=True,exist_ok=True)\n"
        "(out/'source.hlsl').write_text('source')\n"
        "(out/'reject.hlsl').write_text('reject')\n"
    )
    compiler = native / "clang-dxc"
    compiler.write_text(
        "#!/usr/bin/env python3\nimport pathlib,sys\n"
        "a=sys.argv[1:]; out=next(a[i+1] for i,x in enumerate(a) if x=='-Fo')\n"
        "pathlib.Path(out).write_text('object')\n"
        "if 'reject' in a[-1]:\n print('validator rejected'); sys.exit(7)\n"
        "print('compiled')\n"
    )
    split.chmod(0o755)
    compiler.chmod(0o755)
    tests = build / "install/share/hlsl-test-suite/test/Feature"
    tests.mkdir(parents=True)
    for name, shader in (("good.test", "source.hlsl"),
                         ("bad.yaml", "reject.hlsl"),
                         ("inside.test", "source.hlsl")):
        output = "%t/inside.o" if name == "inside.test" else "%t.o"
        (tests / name).write_text(
            f"# RUN: split-file %s %t\n"
            f"# RUN: %dxc_target -T cs_6_5 -Fo {output} %t/{shader}\n"
            "# RUN: %offloader %t/pipeline.yaml %t.o\n"
        )
    (tests / "only-runtime.test").write_text("# RUN: %offloader %s\n")
    return llvm, build, native


