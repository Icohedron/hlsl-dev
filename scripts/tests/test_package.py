def make_install(root, kind="llvm", platform="native"):
    llvm = checkout(root, "llvm-project", "llvm")
    offload = checkout(root, "offload-test-suite", "offload")
    golden = checkout(root, "offload-golden-images", "golden")
    build = (llvm if kind == "llvm" else offload) / (
        "build" + ("." + platform if platform != "native" else "")
    )
    prefix = build / "install"
    (prefix / "bin").mkdir(parents=True)
    if kind == "llvm":
        (prefix / "bin/clang").write_text("compiler")
        (prefix / "bin/clang-dxc").write_text("compiler")
    (prefix / ("bin/offloader.exe" if platform.startswith("windows-")
               else "bin/offloader")).write_text("offloader")
    if kind == "llvm":
        (prefix / "lib/clang/1/include").mkdir(parents=True)
        (prefix / "lib/clang/1/include/hlsl.h").write_text("HLSL")
    (prefix / "share/hlsl-test-suite/test").mkdir(parents=True)
    (prefix / "share/hlsl-test-suite/test/lit.cfg.py").write_text("# suite\n")
    (prefix / "share/hlsl-test-suite/golden-images").mkdir(parents=True)
    (prefix / "share/hlsl-test-suite/golden-images/ref.png").write_bytes(b"PNG")
    (llvm / "llvm/utils/lit/lit").mkdir(parents=True)
    (llvm / "llvm/utils/lit/lit/__init__.py").write_text("# fixture\n")
    (llvm / "llvm/utils/lit/lit/main.py").write_text("def main(): pass\n")
    test_root = build / ("tools/OffloadTest/test" if kind == "llvm" else "test")
    site = test_root / "clang-vk/lit.site.cfg.py"
    site.parent.mkdir(parents=True)
    dist_build = "build" + ("." + platform if platform != "native" else "")
    bin_dir = build / "bin" if kind == "llvm" else llvm / dist_build / "install/bin"
    dxc = root / "host-dxc/bin"
    dxc.mkdir(parents=True)
    site.write_text(
        f"# Autogenerated from {offload / 'test/lit.site.cfg.py.in'}\n"
        "import os\n"
        "def path(value):\n"
        "    return os.path.normpath(os.path.join(os.path.dirname(__file__), value))\n"
        f'config.offloadtest_obj_root = path(r"{test_root.parent}")\n'
        f'config.offloadtest_src_root = path(r"{offload}")\n'
        f'config.offloadtest_tools_dir = path(r"{build / "bin"}")\n'
        f'config.llvm_tools_dir = path(r"{bin_dir}")\n'
        f'config.offloadtest_dxc = path(r"{dxc / "dxc"}")\n'
        f'config.offloadtest_dxc_dir = r"{dxc}"\n'
        f'config.goldenimage_dir = r"{golden}"\n'
        'config.offloadtest_os = "Windows"\n'
        "\nimport lit.llvm\n"
        "lit.llvm.initialize(lit_config, config)\n"
        'lit_config.load_config(config, os.path.join(config.offloadtest_src_root, "test/lit.cfg.py"))\n'
    )
    if kind == "offload":
        dist = llvm / dist_build / "install"
        (dist / "bin").mkdir(parents=True)
        executable = ".exe" if platform.startswith("windows-") else ""
        (dist / f"bin/clang{executable}").write_text("clang")
        (dist / f"bin/clang-dxc{executable}").write_text("compiler")
        (dist / f"bin/FileCheck{executable}").write_text("filecheck")
        (dist / f"bin/split-file{executable}").write_text("split-file")
        (dist / "lib/clang/1/include").mkdir(parents=True)
        (dist / "lib/clang/1/include/hlsl.h").write_text("HLSL")
    return llvm, offload, golden, build, site


def unpack(path, target):
    target.mkdir()
    if path.suffix == ".zip":
        with zipfile.ZipFile(path) as archive:
            archive.extractall(target)
            return archive.namelist()
    with tarfile.open(path, "r:gz") as archive:
        archive.extractall(target, filter="data")
        return archive.getnames()


