def test_standalone_build_and_package_lock_prefix_before_build(workspace, monkeypatch):
    from hlsl_cli import offload, package

    llvm, tree, _, build, _ = make_install(workspace, "offload")
    prefix = llvm / "build/install"
    (prefix / "lib/cmake/llvm").mkdir(parents=True)
    (prefix / "lib/cmake/llvm/LLVMConfig.cmake").touch()
    dxc = workspace / "host-dxc/bin"
    (dxc / "dxc").touch()
    (dxc / "dxv").touch()
    monkeypatch.setenv("HLSL_CMAKE_FLAGS_OFFLOAD", "-G Ninja -DLLVM_DIR=$HD_LLVM_CMAKE_DIR")
    monkeypatch.setenv("HLSL_LOCK_TIMEOUT", "1")
    building = threading.Event()
    package_trying_prefix = threading.Event()
    package_has_prefix = threading.Event()
    offload_has_prefix = threading.Event()
    events = []
    errors = []
    real_offload_lock = offload.build_lock
    real_package_lock = package.build_lock

    @contextmanager
    def offload_lock(root, directory):
        with real_offload_lock(root, directory):
            if directory == prefix:
                offload_has_prefix.set()
            if directory == build:
                building.set()
                # On the old build-first order, allow package to acquire the
                # prefix and expose the opposing nested lock acquisition.
                if not offload_has_prefix.is_set():
                    assert package_has_prefix.wait(2)
            yield

    @contextmanager
    def package_lock(root, directory):
        if directory == prefix:
            package_trying_prefix.set()
        with real_package_lock(root, directory):
            if directory == prefix:
                package_has_prefix.set()
            yield

    def fake_command(argv, directory, *, env=None):
        events.append("build")
        assert package_trying_prefix.wait(2)
        assert not package_has_prefix.is_set()
        if "-B" in argv:
            directory.mkdir(exist_ok=True)
            (directory / "build.ninja").touch()

    def fake_stage(plan, stage):
        events.append("stage")
        (stage / "contents").write_text("packaged")
        return ["contents"]

    def fake_archive(stage, target):
        target.write_text((stage / "contents").read_text())

    monkeypatch.setattr(offload, "build_lock", offload_lock)
    monkeypatch.setattr(package, "build_lock", package_lock)
    monkeypatch.setattr(offload, "_run_command", fake_command)
    monkeypatch.setattr(package, "_stage", fake_stage)
    monkeypatch.setattr(package, "_archive", fake_archive)
    build_request = Request("build", workspace, worktree=str(tree), dxc=str(dxc),
                            targets=("install-offload-tools",))
    archive = workspace / "full.tar.gz"
    package_request = Request("package full", workspace, worktree=str(tree),
                              out=str(archive), no_auto=True)

    def run_action(action, request):
        try:
            action(request)
        except Exception as error:
            errors.append(error)

    worker = threading.Thread(target=run_action, args=(offload.execute, build_request),
                              daemon=True)
    packer = threading.Thread(target=run_action, args=(package.execute, package_request),
                              daemon=True)
    worker.start()
    assert building.wait(2)
    packer.start()
    worker.join(4)
    packer.join(4)
    assert not worker.is_alive() and not packer.is_alive(), "build/package hung"
    assert not errors, errors
    assert events == ["build", "build", "stage"]
    assert archive.read_text() == "packaged"


